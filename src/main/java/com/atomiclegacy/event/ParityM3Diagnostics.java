    private static void recipes(MinecraftServer server, List<String> problems, int[] cases) {
        var rm = server.getRecipeManager();
        List<String> actual = new ArrayList<>();
        for (RecipeHolder<FusionRecipe> h : rm.getAllRecipesFor(HbmRecipeTypes.FUSION.get())) {
            FusionRecipe r = h.value();
            StringBuilder in = new StringBuilder();
            for (FusionRecipe.FusionFluidStack f : r.inputFluids()) in.append(in.isEmpty() ? "" : ",").append(f.fluid().name()).append(':').append(f.amount());
            StringBuilder out = new StringBuilder();
            for (FusionRecipe.FusionFluidStack f : r.outputFluids()) out.append(out.isEmpty() ? "" : ",").append(f.fluid().name()).append(':').append(f.amount());
            String item = r.outputItem().map(s -> BuiltInRegistries.ITEM.getKey(s.getItem()).getPath()).orElse("-");
            actual.add(r.group() + "|" + r.ignitionTemp() + "|" + r.outputTemp() + "|" + r.neutronFlux() + "|" + r.power() + "|"
                    + r.duration() + "|" + in + "|" + out + "|" + item);
        }
        compare(EXPECTED_FUSION, actual, problems, cases, "fusion recipes");
        check(rm.getAllRecipesFor(HbmRecipeTypes.FUSION_BREEDER_ITEM.get()).isEmpty(), problems, cases,
                "fusion breeder has no item recipes (meteorite sword is a hard-coded special case)");
        check(rm.getAllRecipesFor(HbmRecipeTypes.FUSION_BREEDER_FLUID.get()).size() == 3, problems, cases,
                "FluidBreederRecipes: 3 recipes");

        plasma(rm, problems, cases, "dfc_emitter", 3, HbmItems.CIRCUIT_CRYSTAL.get(), 4);
        plasma(rm, problems, cases, "sat_gerald", 10, HbmItems.CIRCUIT_CRYSTAL.get(), 12);
        plasma(rm, problems, cases, "sat_gerald_expensive", 9, HbmItems.CIRCUIT_CRYSTAL.get(), 64);
        plasma(rm, problems, cases, "dfc_stabilizer", 1, BuiltInRegistries.ITEM.get(AtomicLegacy.id("wire_dense_schrabidate")), 16);
        plasma(rm, problems, cases, "hde", 0, BuiltInRegistries.ITEM.get(AtomicLegacy.id("plate_cast_arsenic_bronze")), 2);
        plasma(rm, problems, cases, "hde", 0, BuiltInRegistries.ITEM.get(AtomicLegacy.id("plate_cast_bismuth_bronze")), 2);
        plasma(rm, problems, cases, "expensive_bronze_tubes", 2, BuiltInRegistries.ITEM.get(AtomicLegacy.id("plate_cast_arsenic_bronze")), 4);
    }

    private static void plasma(net.minecraft.world.item.crafting.RecipeManager rm, List<String> problems, int[] cases,
                               String id, int index, net.minecraft.world.item.Item item, int count) {
        var holder = rm.byKey(AtomicLegacy.id("plasma_forge/" + id)).orElse(null);
        if (holder == null || !(holder.value() instanceof PlasmaForgeRecipe recipe)) {
            // the expensive variant is disabled by its load condition in normal mode
            check(id.endsWith("_expensive"), problems, cases, "plasma_forge/" + id + " missing");
            return;
        }
        boolean ok = index < recipe.inputItems().size()
                && recipe.inputItems().get(index).ingredient().test(new ItemStack(item))
                && recipe.inputItems().get(index).count() == count;
        check(ok, problems, cases, "plasma_forge/" + id + " input " + index + " = " + BuiltInRegistries.ITEM.getKey(item) + " x" + count);
    }

    private static void damageTypes(MinecraftServer server, List<String> problems, int[] cases) {
        var registry = server.registryAccess().registryOrThrow(Registries.DAMAGE_TYPE);
        for (var key : List.of(HbmDamageTypes.AMS, HbmDamageTypes.AMS_CORE)) {
            var holder = registry.getHolder(key).orElse(null);
            check(holder != null, problems, cases, "damage type " + key.location() + " registered");
            if (holder != null) {
                check(holder.is(DamageTypeTags.BYPASSES_ARMOR) && holder.is(DamageTypeTags.BYPASSES_ENCHANTMENTS)
                        && holder.is(DamageTypeTags.BYPASSES_RESISTANCE), problems, cases,
                        key.location() + ": setDamageIsAbsolute().setDamageBypassesArmor()");
            }
        }
        check("amsCore".equals(registry.get(HbmDamageTypes.AMS_CORE).msgId()), problems, cases, "amsCore death message id");
    }

