    private static void icf(List<String> problems, int[] cases) throws ReflectiveOperationException {
        ItemStack pellet = IcfPelletItem.setup(IcfPelletItem.Fuel.DEUTERIUM, IcfPelletItem.Fuel.TRITIUM, false);
        checkEq(IcfPelletItem.getFusingDifficulty(pellet), (long) (10_000_000L * (1.00D * 1.05D)), problems, cases, "ICF D/T fusing difficulty");
        ItemStack muon = IcfPelletItem.setup(IcfPelletItem.Fuel.DEUTERIUM, IcfPelletItem.Fuel.TRITIUM, true);
        checkEq(IcfPelletItem.getFusingDifficulty(muon), (long) (10_000_000L * (1.00D * 1.05D)) / 4, problems, cases, "muon catalysed / 4");
        checkEq(IcfPelletItem.react(pellet, 1_000_000L), (long) (1_000_000L * 1.25D * 1.50D), problems, cases, "react heat * reactionMult");

        IcfCoreBlockEntity core = new IcfCoreBlockEntity(BlockPos.ZERO, HbmBlocks.ICF.get().defaultBlockState());
        HbmFluidTank sodium = (HbmFluidTank) field(core, "sodium");
        HbmFluidTank hot = (HbmFluidTank) field(core, "hotSodium");
        sodium.setAmount(1000);
        setField(core, "heat", 4_000_000L);
        invoke(core, "convertSodium", new Class<?>[0]);
        checkEq((long) field(core, "heat"), 4_000_000L - 400L * 1000L, problems, cases, "ICF sodium: 400 TU per mB, min(heat/4/req*3, heat/req)");
        checkEq(hot.amount(), 1000, problems, cases, "ICF hot sodium output");
        core.setItem(IcfCoreBlockEntity.IDENTIFIER_SLOT, FluidIdentifierItem.forFluid(fluid("water")));
        invoke(core, "applyFluidIdentifier", new Class<?>[0]);
        check(sodium.type() == fluid("water") && sodium.amount() == 0, problems, cases, "ICF identifier sets any coolant type");
        invoke(core, "convertSodium", new Class<?>[0]);
        check(hot.type() == fluid("steam") && hot.amount() == 0, problems, cases, "ICF hot tank forced to step.typeProduced");

        Method material = method(com.atomiclegacy.tileentity.IcfPressBlockEntity.class, "fuelForMaterial", String.class);
        check(material.invoke(null, "carbon") == null && material.invoke(null, "graphite") == IcfPelletItem.Fuel.CARBON,
                problems, cases, "ICF press materialMap: MAT_GRAPHITE only");
    }

