    static int run(MinecraftServer server, List<String> problems) {
        int[] cases = {0};
        ServerLevel level = server.overworld();
        site = 0;
        try {
            recipes(server, problems, cases);
            damageTypes(server, problems, cases);
            dfcCore(level, problems, cases);
            dfcBeam(level, problems, cases);
            dfcInjector(level, problems, cases);
            tungstenCrate(level, problems, cases);
            torus(level, problems, cases);
            breeder(level, problems, cases);
            watzFunctions(problems, cases);
            watzRedstone(level, problems, cases);
            icf(problems, cases);
        } catch (RuntimeException | ReflectiveOperationException e) {
            AtomicLegacy.LOGGER.error("Parity M3 diagnostics crashed", e);
            problems.add("M3 diagnostics crashed: " + e);
        } finally {
            for (int[] chunk : FORCED) level.setChunkForced(chunk[0], chunk[1], false);
            FORCED.clear();
        }
        return cases[0];
    }

