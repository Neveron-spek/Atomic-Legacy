    private static double squirt(double x) {
        return Math.sqrt(x + 1D / ((x + 2D) * (x + 2D))) - 1D / (x + 2D);
    }

    private static void watzFunctions(List<String> problems, int[] cases) {
        near(WatzPelletItem.Type.DU.absorb.apply(100.0D), 2.0D, problems, cases, "DU absorb: (x/100)^2 * 1 + 1");
        near(WatzPelletItem.Type.LEAD.absorb.apply(0.0D), squirt(0.0D) * 10.0D, problems, cases, "LEAD absorb: squirt(x) * 10");
        near(WatzPelletItem.Type.MEU.burn.apply(100.0D), squirt(100.0D) * 75.0D, problems, cases, "MEU burn: squirt(x) * 75");
        near(WatzPelletItem.Type.SCHRABIDIUM.heatDiv.apply(0.0D), squirt(100.0D) / 10.0D, problems, cases, "SCHRABIDIUM heatDiv: squirt(x + 100) / 10");
        near(WatzPelletItem.Type.NQD.burn.apply(10.0D), 20.0D, problems, cases, "NQD burn: x * 2");
        near(WatzPelletItem.Type.HES.mudContent, 0.005D / 2D, problems, cases, "mudContent halved");
    }

    private static void watzRedstone(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 80);
        level.setBlock(pos, HbmBlocks.WATZ.get().defaultBlockState(), 2 | 16);
        if (!(level.getBlockEntity(pos) instanceof WatzBlockEntity watz)) {
            check(false, problems, cases, "watz block entity");
            cleanup(level, pos);
            return;
        }
        Method on = method(watz, "hasPumpAndRedstone", net.minecraft.world.level.Level.class);
        level.setBlock(pos.above(3), HbmBlocks.WATZ_PUMP.get().defaultBlockState(), 2 | 16);
        level.setBlock(pos.above(5), Blocks.REDSTONE_BLOCK.defaultBlockState(), 3);
        check((boolean) on.invoke(watz, level), problems, cases, "watz on: pump at y+3, power source at y+5");
        level.setBlock(pos.above(5), Blocks.AIR.defaultBlockState(), 3);
        level.setBlock(pos.above(4), Blocks.REDSTONE_BLOCK.defaultBlockState(), 3);
        check(!(boolean) on.invoke(watz, level), problems, cases, "watz off: getIndirectPowerLevelTo(y + 5) only");
        level.setBlock(pos.above(4), Blocks.AIR.defaultBlockState(), 3);
        cleanup(level, pos);
    }

