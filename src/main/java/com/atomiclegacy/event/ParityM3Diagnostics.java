    private static HbmFluidDefinition fluid(String name) {
        return HbmFluids.byName(name).orElseThrow(() -> new IllegalStateException("missing fluid " + name));
    }

    private static Object field(Object owner, String name) throws ReflectiveOperationException {
        return findField(owner.getClass(), name).get(owner);
    }

    private static void setField(Object owner, String name, Object value) throws ReflectiveOperationException {
        findField(owner.getClass(), name).set(owner, value);
    }

    private static Field findField(Class<?> type, String name) throws NoSuchFieldException {
        for (Class<?> c = type; c != null; c = c.getSuperclass()) {
            try {
                Field f = c.getDeclaredField(name);
                f.setAccessible(true);
                return f;
            } catch (NoSuchFieldException ignored) {
            }
        }
        throw new NoSuchFieldException(name);
    }

    private static Method method(Object owner, String name, Class<?>... types) throws NoSuchMethodException {
        return method(owner.getClass(), name, types);
    }

    private static Method method(Class<?> type, String name, Class<?>... types) throws NoSuchMethodException {
        Method m = type.getDeclaredMethod(name, types);
        m.setAccessible(true);
        return m;
    }

    private static Object invoke(Object owner, String name, Class<?>[] types, Object... args) throws ReflectiveOperationException {
        return method(owner, name, types).invoke(owner, args);
    }

    private static void check(boolean condition, List<String> problems, int[] cases, String message) {
        cases[0]++;
        if (!condition) problems.add("M3: " + message);
    }

    private static void checkEq(long actual, long expected, List<String> problems, int[] cases, String message) {
        check(actual == expected, problems, cases, message + ": " + actual + " expected " + expected);
    }

    private static void near(double actual, double expected, List<String> problems, int[] cases, String message) {
        check(Math.abs(actual - expected) < 1e-9, problems, cases, message + ": " + actual + " expected " + expected);
    }

    private static void compare(List<String> expectedIn, List<String> actualIn, List<String> problems, int[] cases, String what) {
        List<String> expected = new ArrayList<>(expectedIn);
        List<String> actual = new ArrayList<>(actualIn);
        Collections.sort(expected);
        Collections.sort(actual);
        List<String> missing = new ArrayList<>(expected);
        for (String a : actual) missing.remove(a);
        List<String> extra = new ArrayList<>(actual);
        for (String e : expected) extra.remove(e);
        cases[0] += expected.size();
        if (!missing.isEmpty() || !extra.isEmpty()) problems.add("M3: " + what + " differ: missing " + missing + ", extra " + extra);
    }

    private static BlockPos pad(ServerLevel level, int y) {
        int index = site++;
        BlockPos pos = new BlockPos(BASE_X + index * SPACING, y, BASE_Z);
        for (int cx = (pos.getX() - 24) >> 4; cx <= (pos.getX() + 24) >> 4; cx++) {
            for (int cz = (pos.getZ() - 24) >> 4; cz <= (pos.getZ() + 24) >> 4; cz++) {
                level.setChunkForced(cx, cz, true);
                level.getChunk(cx, cz);
                FORCED.add(new int[] {cx, cz});
            }
        }
        for (int dx = -4; dx <= 4; dx++) for (int dy = -1; dy <= 8; dy++) for (int dz = -4; dz <= 4; dz++) {
            BlockPos p = pos.offset(dx, dy, dz);
            level.setBlock(p, dy < 0 ? Blocks.STONE.defaultBlockState() : Blocks.AIR.defaultBlockState(), 2 | 16);
        }
        return pos;
    }

    private static void cleanup(ServerLevel level, BlockPos pos) {
        for (BlockPos cursor : BlockPos.betweenClosed(pos.offset(-4, 0, -4), pos.offset(4, 8, 4))) {
            BlockEntity be = level.getBlockEntity(cursor);
            if (be instanceof net.minecraft.world.Container container) container.clearContent();
            if (!level.getBlockState(cursor).isAir()) level.setBlock(cursor, Blocks.AIR.defaultBlockState(), 2 | 16);
        }
    }
