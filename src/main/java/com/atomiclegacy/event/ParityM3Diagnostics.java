    private static void torus(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockState state = HbmBlocks.FUSION_TORUS.get().defaultBlockState();
        FusionMachineBlockEntity torus = new FusionMachineBlockEntity(BlockPos.ZERO, state, FusionMachineBlock.Kind.TORUS);
        RecipeHolder<FusionRecipe> dt = level.getRecipeManager().byKey(AtomicLegacy.id("fusion/dt"))
                .filter(h -> h.value() instanceof FusionRecipe).map(h -> {
                    @SuppressWarnings("unchecked") RecipeHolder<FusionRecipe> cast = (RecipeHolder<FusionRecipe>) h;
                    return cast;
                }).orElse(null);
        if (dt == null) {
            check(false, problems, cases, "fusion/dt recipe");
            return;
        }
        invoke(torus, "configureTorusTanks", new Class<?>[] {FusionRecipe.class}, dt.value());
        Method canProcess = method(torus, "canProcessTorus", FusionRecipe.class, double.class);
        Method factor = method(torus, "torusProcessFactor", FusionRecipe.class);
        setField(torus, "power", 24_999L);
        check(!(boolean) canProcess.invoke(torus, dt.value(), 1.0D), problems, cases, "torus needs the full recipe power stored");
        setField(torus, "power", 25_000L);
        check((boolean) canProcess.invoke(torus, dt.value(), 1.0D), problems, cases, "torus runs with recipe.power stored");
        torus.tank(0).setAmount(1000);
        torus.tank(1).setAmount(4000);
        setField(torus, "power", 10_000_000L);
        double f = (double) factor.invoke(torus, dt.value());
        check(Math.abs(f - 0.5D) < 1e-9, problems, cases, "speed factor = min(getSpeedScaled) (1000/4000 -> 0.5): " + f);
        torus.tank(0).setAmount(3);
        check(!(boolean) canProcess.invoke(torus, dt.value(), 0.5D), problems, cases, "partial fuel below ceil(fill*speed) blocks");
        torus.tank(0).setAmount(0);
        check(!(boolean) canProcess.invoke(torus, dt.value(), 0.0D), problems, cases, "processSpeed 0 blocks");
    }

    private static void breeder(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockState state = HbmBlocks.FUSION_TORUS.get().defaultBlockState();
        FusionMachineBlockEntity breeder = new FusionMachineBlockEntity(new BlockPos(BASE_X, 300, BASE_Z - 200), state, FusionMachineBlock.Kind.BREEDER);
        breeder.setLevel(level);
        breeder.setItem(FusionMachineBlockEntity.BREEDER_INPUT_SLOT, new ItemStack(HbmItems.METEORITE_SWORD_IRRADIATED.get()));
        breeder.receiveFusionPower(0L, 6_000.0D, 1F, 1F, 1F);
        check(breeder.getItem(FusionMachineBlockEntity.BREEDER_OUTPUT_SLOT).isEmpty(), problems, cases, "breeder: progress 6000 <= capacity");
        breeder.receiveFusionPower(0L, 6_000.0D, 1F, 1F, 1F);
        check(breeder.getItem(FusionMachineBlockEntity.BREEDER_OUTPUT_SLOT).is(HbmItems.METEORITE_SWORD_FUSED.get())
                        && breeder.getItem(FusionMachineBlockEntity.BREEDER_INPUT_SLOT).isEmpty(),
                problems, cases, "breeder: irradiated sword -> fused sword after > 10000 flux");
        breeder.setItem(FusionMachineBlockEntity.BREEDER_INPUT_SLOT, new ItemStack(HbmItems.METEORITE_SWORD_IRRADIATED.get()));
        check(!(boolean) invoke(breeder, "canProcessBreederSolid", new Class<?>[] {net.minecraft.world.level.Level.class}, level),
                problems, cases, "breeder: sword needs an empty output slot");
        breeder.setLevel(null);
    }

