    private static void dfcCore(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 80);
        level.setBlock(pos, HbmBlocks.DFC_CORE.get().defaultBlockState(), 3);
        if (!(level.getBlockEntity(pos) instanceof DfcCoreBlockEntity core)) {
            check(false, problems, cases, "dfc_core block entity");
            return;
        }
        check(core.fluidHandler(null) == null, problems, cases, "TileEntityCore has no fluid ports");
        check(core.getSlotsForFace(Direction.UP).length == 0, problems, cases, "TileEntityCore: no automation slots");
        core.setItem(DfcCoreBlockEntity.CATALYST_LEFT_SLOT, new ItemStack(HbmItems.AMS_CATALYST_LITHIUM.get()));
        core.setItem(DfcCoreBlockEntity.CATALYST_RIGHT_SLOT, new ItemStack(HbmItems.AMS_CATALYST_LITHIUM.get()));
        core.setItem(DfcCoreBlockEntity.CORE_SLOT, new ItemStack(HbmItems.AMS_CORE_SING.get()));
        core.tank(0).setAmount(1000);
        core.tank(1).setAmount(1000);
        DfcCoreBlockEntity.tick(level, pos, level.getBlockState(pos), core);
        check(core.color() == 0xFF2727, problems, cases, "catalyst colour average " + Integer.toHexString(core.color()));
        long out = core.burn(10_000L);
        checkEq(out, (long) (10_000L * 500 * 1.5F * 1.7F), problems, cases, "burn(10000) sing core D/T");
        checkEq(core.tank(0).amount(), 990, problems, cases, "burn demand ceil(J/1000)");
        checkEq(core.heat(), 1, problems, cases, "burn heat ceil(J/10000)");
        core.stabilize(5);
        DfcCoreBlockEntity.tick(level, pos, level.getBlockState(pos), core);
        check(!core.meltdownTick(), problems, cases, "heat < field: no meltdown");
        checkEq(core.field(), 4, problems, cases, "field decays by 1 per tick");

        double radBefore = ChunkRadiationData.get(level).getRadiation(pos);
        NukeExplosionManager.registerFieldDisturber(level, pos, 20);
        setField(core, "field", 0);
        setField(core, "heat", 50);
        DfcCoreBlockEntity.tick(level, pos, level.getBlockState(pos), core);
        check(core.meltdownTick(), problems, cases, "suppressed meltdown sets meltdownTick");
        int fill = 990 + 990;
        int expectedSize = Math.max(Math.min(fill * (50 * 10) / 256_000, 1000), 50);
        checkEq(core.lastMeltdownSize(), -expectedSize, problems, cases, "meltdown size (suppressed)");
        double radAfter = ChunkRadiationData.get(level).getRadiation(pos);
        check(Math.abs(radAfter - radBefore - 100.0D) < 0.01D, problems, cases, "suppressed meltdown incrementRad(100): " + (radAfter - radBefore));
        check(!NukeExplosionManager.hasPendingTasks(level), problems, cases, "no explosion scheduled");
        cleanup(level, pos);
    }

    private static void dfcBeam(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 80);
        BlockPos target = pos.east(3);
        level.setBlock(pos, HbmBlocks.DFC_EMITTER.get().defaultBlockState().setValue(DfcComponentBlock.FACING, Direction.EAST), 3);
        level.setBlock(target, HbmBlocks.DFC_RECEIVER.get().defaultBlockState().setValue(DfcComponentBlock.FACING, Direction.WEST), 3);
        if (!(level.getBlockEntity(pos) instanceof DfcEmitterBlockEntity emitter)
                || !(level.getBlockEntity(target) instanceof DfcReceiverBlockEntity receiver)) {
            check(false, problems, cases, "dfc emitter/receiver block entities");
            return;
        }
        emitter.tank().setAmount(1000);
        receiver.tank().setAmount(1000);
        setField(emitter, "power", 1_000_000_000L);
        setField(emitter, "watts", 10);
        setField(emitter, "on", true);
        DfcEmitterBlockEntity.tick(level, pos, level.getBlockState(pos), emitter);
        checkEq((long) field(emitter, "power"), 1_000_000_000L - 1_000_000_000L * 10 / 2000, problems, cases, "emitter demand maxPower*watts/2000");
        checkEq(receiver.joules(), 10 * 100 * 95 / 100, problems, cases, "emitter beam joules*95/100");
        DfcReceiverBlockEntity.tick(level, target, level.getBlockState(target), receiver);
        checkEq(receiver.power(), 950L * 5000L, problems, cases, "receiver power = joules * 5000");
        checkEq(receiver.tank().amount(), 980, problems, cases, "receiver cryogel 20 mB per tick");
        DfcEmitterBlockEntity.tick(level, pos, level.getBlockState(pos), emitter);
        checkEq(emitter.tank().amount(), 980, problems, cases, "emitter cryogel 20 mB while prev > 0");
        cleanup(level, pos);
    }

    private static void dfcInjector(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 80);
        level.setBlock(pos, HbmBlocks.DFC_INJECTOR.get().defaultBlockState().setValue(DfcComponentBlock.FACING, Direction.EAST), 3);
        level.setBlock(pos.east(2), HbmBlocks.DFC_CORE.get().defaultBlockState(), 3);
        if (!(level.getBlockEntity(pos) instanceof DfcInjectorBlockEntity injector)
                || !(level.getBlockEntity(pos.east(2)) instanceof DfcCoreBlockEntity core)) {
            check(false, problems, cases, "dfc injector/core block entities");
            return;
        }
        HbmFluidTank[] tanks = (HbmFluidTank[]) field(injector, "tanks");
        tanks[1].setAmount(500);
        injector.setItem(DfcInjectorBlockEntity.INPUT_0, FluidIdentifierItem.forFluid(fluid("hydrogen")));
        DfcInjectorBlockEntity.tick(level, pos, level.getBlockState(pos), injector);
        check(tanks[0].type() == fluid("hydrogen") && tanks[0].amount() == 0, problems, cases, "identifier sets injector tank type and empties it");
        check(injector.getItem(DfcInjectorBlockEntity.INPUT_0).isEmpty() && !injector.getItem(DfcInjectorBlockEntity.OUTPUT_0).isEmpty(),
                problems, cases, "identifier moves to the output slot");
        check(core.tank(0).type() == fluid("hydrogen"), problems, cases, "empty core tank adopts the injector type");
        checkEq(core.tank(1).amount(), 500, problems, cases, "injector moves min(fill, space) to the core");
        cleanup(level, pos);
        cleanup(level, pos.east(2));
    }

