package com.atomiclegacy.event;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.atomiclegacy.AtomicLegacy;
import com.atomiclegacy.blocks.LegacyBlastResistance;
import com.atomiclegacy.registry.HbmBlocks;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.IntegerProperty;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * [parity T3: diagnostics] Explosion resistance of every mod block against the original (936c60c4).
 * 1.7.10: setResistance(r) stores r*3, setHardness(h) raises it to h*5, getExplosionResistance() returns it /5;
 * the 1.21 port uses the property directly, so it must hold the original effective value (0.6*r).
 * Table: legacy/atomiclegacy/parity-t3-resistance.json, generated by work/parity_t3_resistance.py.
 */
final class ParityT3Diagnostics {
    private ParityT3Diagnostics() {
    }

    static int run(MinecraftServer server, List<String> problems) {
        int[] cases = {0};
        ServerLevel level = server.overworld();
        Map<String, JsonObject> byId = new HashMap<>();
        Map<String, JsonObject> byField = new HashMap<>();
        try (var input = ParityT3Diagnostics.class.getResourceAsStream("/legacy/atomiclegacy/parity-t3-resistance.json")) {
            if (input == null) {
                problems.add("T3: missing parity-t3-resistance.json");
                return 0;
            }
            for (var element : JsonParser.parseReader(new InputStreamReader(input, StandardCharsets.UTF_8)).getAsJsonArray()) {
                JsonObject row = element.getAsJsonObject();
                byId.putIfAbsent(row.get("id").getAsString(), row);
                byField.putIfAbsent(row.get("field").getAsString(), row);
            }
        } catch (Exception e) {
            problems.add("T3: cannot read table " + e);
            return 0;
        }

        BlockPos probe = new BlockPos(31000, 300, 31000);
        List<String> dump = new ArrayList<>();
        dump.add("id\toriginal\tproperty\tstate\texpected\tstatus");
        int matched = 0;
        int unmatched = 0;
        for (Block block : BuiltInRegistries.BLOCK) {
            var key = BuiltInRegistries.BLOCK.getKey(block);
            if (!AtomicLegacy.MOD_ID.equals(key.getNamespace())) {
                continue;
            }
            String path = key.getPath();
            String original = LegacyBlastResistance.originalId(path);
            JsonObject row = byId.containsKey(original) ? byId.get(original) : byField.get(original);
            Float tableValue = LegacyBlastResistance.lookup(path);
            float property = block.getExplosionResistance();
            BlockState state = block.defaultBlockState();
            float positional;
            try {
                positional = state.getExplosionResistance(level, probe, null);
            } catch (RuntimeException e) {
                positional = Float.NaN;
            }
            if (row == null && tableValue != null) {
                // port-only stairs/slab of an original block (BlockStairs copies the parent)
                matched++;
                cases[0]++;
                boolean ok = near(property, tableValue) && near(positional, tableValue);
                if (!ok) problems.add("T3 " + path + " resistance property/state " + property + "/" + positional + " expected " + tableValue + " (parent block)");
                dump.add(path + "\tparent\t" + property + "\t" + positional + "\t" + tableValue + "\t" + (ok ? "ok" : "MISMATCH"));
                continue;
            }
            if (row == null) {
                unmatched++;
                dump.add(path + "\t-\t" + property + "\t" + positional + "\t-\tno-original");
                continue;
            }
            matched++;
            float expected = value(row.get("expected").getAsString());
            boolean multiSlab = row.has("variants") && row.get("variants").isJsonArray();
            // BlockMultiSlab: own value (getExplosionResistance(null), used by nukes) vs positional value per variant below
            boolean ok = near(property, expected) && (multiSlab || near(positional, expected));
            cases[0]++;
            if (!ok) {
                problems.add("T3 " + path + " resistance property/state " + property + "/" + positional + " expected " + expected
                        + " (original " + row.get("field").getAsString() + " setResistance " + row.get("resistance_arg") + ")");
            }
            dump.add(path + "\t" + row.get("field").getAsString() + "\t" + property + "\t" + positional + "\t" + expected + "\t" + (ok ? "ok" : "MISMATCH"));
            if (row.has("variants") && row.get("variants").isJsonArray()) {
                var variants = row.get("variants").getAsJsonArray();
                var prop = state.getBlock().getStateDefinition().getProperty("variant");
                if (!(prop instanceof IntegerProperty variantProperty)) {
                    problems.add("T3 " + path + " has no variant property for BlockMultiSlab resistance");
                    continue;
                }
                for (int i = 0; i < variants.size(); i++) {
                    if (!variantProperty.getPossibleValues().contains(i)) {
                        problems.add("T3 " + path + " lacks variant " + i);
                        continue;
                    }
                    JsonObject parent = byField.get(variants.get(i).getAsString());
                    float want = value(parent.get("expected").getAsString());
                    float got = state.setValue(variantProperty, i).getExplosionResistance(level, probe, null);
                    cases[0]++;
                    if (!near(got, want)) {
                        problems.add("T3 " + path + " variant " + i + " resistance " + got + " expected " + want + " (" + variants.get(i).getAsString() + ")");
                    }
                    dump.add(path + "#" + i + "\t" + variants.get(i).getAsString() + "\t-\t" + got + "\t" + want + "\t" + (near(got, want) ? "ok" : "MISMATCH"));
                }
            }
        }
        dump.add("# matched=" + matched + " unmatched=" + unmatched);
        try {
            Files.write(Path.of("parity-t3-resistance.tsv"), dump, StandardCharsets.UTF_8);
        } catch (Exception e) {
            problems.add("T3: cannot write dump " + e);
        }

        // Control blasts (vanilla algorithm, identical in 1.7.10 and 1.21: rays of power P*(0.7..1.3), step 0.3,
        // loss (resistance + 0.3) * 0.3 per solid block, 0.225 per step). Explosion at the centre of the air cell
        // west of the target: the target is reached on the third step, so it breaks iff
        // f0 - 0.45 - (R + 0.3) * 0.3 > 0 with f0 < 1.3 * P. P = 2.7: R = 6 (ore_uranium, original setResistance(10))
        // breaks; R >= 9.9 never breaks (ore_uranium with an unconverted 10 would also survive).
        blast(level, problems, cases, 0, HbmBlocks.ORE_URANIUM.get(), true);
        blast(level, problems, cases, 8, HbmBlocks.BRICK_CONCRETE.get(), false);
        return cases[0];
    }

    private static void blast(ServerLevel level, List<String> problems, int[] cases, int offset, Block target, boolean breaks) {
        BlockPos pos = new BlockPos(31000 + offset * 16, 200, 31000);
        level.getChunkAt(pos);
        for (BlockPos p : BlockPos.betweenClosed(pos.offset(-6, -6, -6), pos.offset(6, 6, 6))) {
            level.setBlock(p, Blocks.AIR.defaultBlockState(), 2 | 16);
        }
        level.setBlock(pos, target.defaultBlockState(), 2 | 16);
        BlockPos centre = pos.west();
        level.explode(null, centre.getX() + 0.5D, centre.getY() + 0.5D, centre.getZ() + 0.5D, 2.7F, Level.ExplosionInteraction.TNT);
        boolean broken = !level.getBlockState(pos).is(target);
        cases[0]++;
        if (broken != breaks) {
            problems.add("T3 blast P=2.7 next to " + BuiltInRegistries.BLOCK.getKey(target) + " (resistance "
                    + target.getExplosionResistance() + "): broken=" + broken + ", original " + (breaks ? "breaks" : "survives"));
        }
        level.setBlock(pos, Blocks.AIR.defaultBlockState(), 2 | 16);
    }

    /** Used by older batch diagnostics that pinned the literal 1.7.10 setResistance argument. */
    static boolean resistanceMatches(Block block) {
        Float expected = LegacyBlastResistance.lookup(BuiltInRegistries.BLOCK.getKey(block).getPath());
        return expected != null && near(block.getExplosionResistance(), expected);
    }

    private static float value(String text) {
        return "Infinity".equals(text) ? Float.POSITIVE_INFINITY : Float.parseFloat(text);
    }

    private static boolean near(float actual, float expected) {
        if (Float.isInfinite(expected) || Float.isInfinite(actual)) {
            return actual == expected;
        }
        return Math.abs(actual - expected) <= 1.0E-4F * Math.max(1.0F, Math.abs(expected));
    }
}
