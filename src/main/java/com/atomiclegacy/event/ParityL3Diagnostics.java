    /** TileEntityMachineCatalyticCracker: every 5 ticks two operations of 100 mB + 200 mB steam, +2 mB spent steam (cap 800). */
    private static void cracker(ServerLevel level, ServerLevelData data, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 200);
        level.setBlock(pos, HbmBlocks.MACHINE_CATALYTIC_CRACKER.get().defaultBlockState(), 2 | 16);
        if (!(level.getBlockEntity(pos) instanceof CatalyticCrackerBlockEntity cracker)) {
            check(false, problems, cases, "cracker block entity missing");
            return;
        }
        HbmFluidTank[] tanks = (HbmFluidTank[]) field(cracker, "tanks");
        checkEq(tanks[4].capacity(), 800, problems, cases, "cracker spent steam capacity");
        checkEq(tanks[0].capacity(), 4000, problems, cases, "cracker input capacity");
        checkEq(tanks[1].capacity(), 8000, problems, cases, "cracker steam capacity");
        tanks[0].setType(fluid("bitumen"));
        tanks[0].setAmount(4000);
        tanks[1].setType(fluid("steam"));
        tanks[1].setAmount(8000);
        data.setGameTime(1000L);
        CatalyticCrackerBlockEntity.tick(level, pos, level.getBlockState(pos), cracker);
        checkEq(tanks[0].amount(), 3800, problems, cases, "cracker input after one crack");
        checkEq(tanks[1].amount(), 7600, problems, cases, "cracker steam after one crack");
        checkEq(tanks[2].amount(), 160, problems, cases, "cracker oil out");
        checkEq(tanks[3].amount(), 40, problems, cases, "cracker aromatics out");
        checkEq(tanks[4].amount(), 4, problems, cases, "cracker spent steam out");
        data.setGameTime(1001L);
        CatalyticCrackerBlockEntity.tick(level, pos, level.getBlockState(pos), cracker);
        checkEq(tanks[0].amount(), 3800, problems, cases, "cracker idles off the 5-tick cycle");
        tanks[4].setAmount(799);
        data.setGameTime(1005L);
        CatalyticCrackerBlockEntity.tick(level, pos, level.getBlockState(pos), cracker);
        checkEq(tanks[0].amount(), 3800, problems, cases, "cracker blocked by full spent steam tank");
        tanks[0].setType(fluid("water"));
        CatalyticCrackerBlockEntity.tick(level, pos, level.getBlockState(pos), cracker);
        check(tanks[2].type().isNone() && tanks[2].amount() == 0, problems, cases, "cracker voids outputs for an uncrackable input");
        cleanup(level, pos);
    }

    /** TileEntityMachineRefinery: 100 mB per tick for 5 HE, 50/25/15/10 mB, sulfur every maxSulfur = 10 operations. */
    private static void refinery(ServerLevel level, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, 200);
        level.setBlock(pos, HbmBlocks.MACHINE_REFINERY.get().defaultBlockState(), 2 | 16);
        if (!(level.getBlockEntity(pos) instanceof RefineryBlockEntity refinery)) {
            check(false, problems, cases, "refinery block entity missing");
            return;
        }
        refinery.inputTank().setType(fluid("hotoil"));
        refinery.inputTank().setAmount(2000);
        setField(refinery, "power", 1000L);
        for (int i = 0; i < 10; i++) RefineryBlockEntity.tick(level, pos, level.getBlockState(pos), refinery);
        checkEq(refinery.inputTank().amount(), 1000, problems, cases, "refinery input after 10 ticks");
        checkEq((long) field(refinery, "power"), 950, problems, cases, "refinery power after 10 ticks");
        checkEq(refinery.outputTank(0).amount(), 500, problems, cases, "refinery heavy oil");
        checkEq(refinery.outputTank(1).amount(), 250, problems, cases, "refinery naphtha");
        checkEq(refinery.outputTank(2).amount(), 150, problems, cases, "refinery light oil");
        checkEq(refinery.outputTank(3).amount(), 100, problems, cases, "refinery petroleum");
        ItemStack sulfur = refinery.getItem(RefineryBlockEntity.ITEM_OUTPUT_SLOT);
        check(sulfur.getCount() == 1 && "sulfur".equals(BuiltInRegistries.ITEM.getKey(sulfur.getItem()).getPath()), problems, cases,
                "refinery byproduct after 10 operations: " + sulfur);
        checkEq(RefineryBlockEntity.INPUT_CAPACITY, 64_000, problems, cases, "refinery input capacity");
        checkEq(RefineryBlockEntity.OUTPUT_CAPACITY, 24_000, problems, cases, "refinery output capacity");
        checkEq(RefineryBlockEntity.MAX_POWER, 1_000, problems, cases, "refinery max power");
        // MachineRefinery#onBlockExploded / burning branch / IRepairable#tryExtinguish
        net.minecraft.world.level.Explosion boom = new net.minecraft.world.level.Explosion(level, null, pos.getX(), pos.getY(), pos.getZ(), 1.0F, false,
                net.minecraft.world.level.Explosion.BlockInteraction.KEEP);
        refinery.handleExplosion(boom);
        refinery.handleExplosion(boom);
        check(refinery.isDamaged() && refinery.isOnFire() && level.getBlockEntity(pos) == refinery, problems, cases, "refinery damaged and burning after an explosion");
        int input = refinery.inputTank().amount();
        RefineryBlockEntity.tick(level, pos, level.getBlockState(pos), refinery);
        checkEq(refinery.inputTank().amount(), input - 10, problems, cases, "burning refinery loses 10 mB per tank and tick");
        checkEq(refinery.outputTank(0).amount(), 490, problems, cases, "burning refinery does not refine");
        refinery.tryExtinguish(true, false);
        check(!refinery.isOnFire(), problems, cases, "CO2 extinguishes the refinery");
        refinery.clearContent();
        cleanup(level, pos);
    }

    /**
     * TileEntityMachineOilWell: 100 HE per tick, an operation every 50 ticks; drills one oil_pipe per operation,
     * sucks 500 mB oil + 100..500 mB gas from an ore_oil reached through ore_oil_empty, drains it with 5 %.
     */
    private static void derrick(ServerLevel level, ServerLevelData data, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, level.getMinBuildHeight() + 8);
        level.setBlock(pos.below(), Blocks.STONE.defaultBlockState(), 2 | 16);
        level.setBlock(pos.below(2), HbmBlocks.ORE_OIL_EMPTY.get().defaultBlockState(), 2 | 16);
        BlockPos ore = pos.below(2).east();
        level.setBlock(ore, HbmBlocks.ORE_OIL.get().defaultBlockState(), 2 | 16);
        level.setBlock(pos, HbmBlocks.MACHINE_WELL.get().defaultBlockState(), 2 | 16);
        if (!(level.getBlockEntity(pos) instanceof OilDerrickBlockEntity derrick)) {
            check(false, problems, cases, "derrick block entity missing");
            return;
        }
        checkEq(OilDerrickBlockEntity.Kind.PUMPJACK.oilPerDeposit(), 750, problems, cases, "pumpjack oil per deposit");
        checkEq(OilDerrickBlockEntity.Kind.PUMPJACK.delay(), 25, problems, cases, "pumpjack delay");
        HbmFluidTank oil = derrick.oilTank();
        HbmFluidTank gas = derrick.gasTank();
        long t = 50_000L;
        setField(derrick, "power", 100_000L);
        data.setGameTime(t);
        OilDerrickBlockEntity.tick(level, pos, level.getBlockState(pos), derrick);
        check(level.getBlockState(pos.below()).is(HbmBlocks.OIL_PIPE.get()), problems, cases, "derrick drills the first pipe");
        checkEq((long) field(derrick, "power"), 99_900, problems, cases, "derrick power per tick");
        int sucks = 0;
        boolean gasInRange = true;
        for (int op = 0; op < 400 && level.getBlockState(ore).is(HbmBlocks.ORE_OIL.get()); op++) {
            t += 50;
            data.setGameTime(t);
            oil.setAmount(0);
            gas.setAmount(0);
            setField(derrick, "power", 100_000L);
            OilDerrickBlockEntity.tick(level, pos, level.getBlockState(pos), derrick);
            sucks++;
            if (oil.amount() != 500) {
                check(false, problems, cases, "derrick oil per suck " + oil.amount());
                break;
            }
            gasInRange &= gas.amount() >= 100 && gas.amount() <= 500;
        }
        check(gasInRange, problems, cases, "derrick gas per suck within 100..500");
        check(level.getBlockState(ore).is(HbmBlocks.ORE_OIL_EMPTY.get()), problems, cases, "derrick depletes ore_oil to ore_oil_empty after " + sucks + " sucks");
        t += 50;
        data.setGameTime(t);
        setField(derrick, "power", 100_000L);
        oil.setAmount(0);
        OilDerrickBlockEntity.tick(level, pos, level.getBlockState(pos), derrick);
        check(oil.amount() == 0 && level.getBlockState(pos.below(2)).is(HbmBlocks.OIL_PIPE.get()), problems, cases,
                "derrick drills through an exhausted deposit");
        derrick.clearContent();
        cleanup(level, pos);
    }

    /** TileEntityMachineFrackingTower: 5000 HE/t, every 20 ticks; ore_bedrock_oil gives 100 mB oil + 10..50 gas for 10 mB FRACKSOL, never depletes. */
    private static void fracking(ServerLevel level, ServerLevelData data, List<String> problems, int[] cases) throws ReflectiveOperationException {
        BlockPos pos = pad(level, level.getMinBuildHeight() + 8);
        level.setBlock(pos.below(), Blocks.STONE.defaultBlockState(), 2 | 16);
        level.setBlock(pos.below(2), HbmBlocks.ORE_BEDROCK_OIL.get().defaultBlockState(), 2 | 16);
        level.setBlock(pos, HbmBlocks.MACHINE_FRACKING_TOWER.get().defaultBlockState(), 2 | 16);
        if (!(level.getBlockEntity(pos) instanceof FrackingTowerBlockEntity tower)) {
            check(false, problems, cases, "fracking tower block entity missing");
            return;
        }
        HbmFluidTank oil = (HbmFluidTank) field(tower, "oilTank");
        HbmFluidTank gas = (HbmFluidTank) field(tower, "gasTank");
        HbmFluidTank sol = (HbmFluidTank) field(tower, "fracksolTank");
        long t = 60_000L;
        data.setGameTime(t);
        setField(tower, "power", 5_000_000L);
        FrackingTowerBlockEntity.tick(level, pos, level.getBlockState(pos), tower);
        check(level.getBlockState(pos.below()).is(HbmBlocks.OIL_PIPE.get()), problems, cases, "fracking tower drills the first pipe");
        checkEq((long) field(tower, "power"), 4_995_000, problems, cases, "fracking tower power per tick");
        t += 20;
        data.setGameTime(t);
        FrackingTowerBlockEntity.tick(level, pos, level.getBlockState(pos), tower);
        checkEq(oil.amount(), 0, problems, cases, "fracking tower without FRACKSOL pumps nothing");
        checkEq((int) field(tower, "indicator"), 3, problems, cases, "fracking tower indicator without FRACKSOL");
        sol.setType(fluid("fracksol"));
        sol.setAmount(1000);
        for (int op = 0; op < 3; op++) {
            t += 20;
            data.setGameTime(t);
            setField(tower, "power", 5_000_000L);
            FrackingTowerBlockEntity.tick(level, pos, level.getBlockState(pos), tower);
        }
        checkEq(oil.amount(), 300, problems, cases, "fracking tower bedrock oil");
        check(gas.amount() >= 30 && gas.amount() <= 150, problems, cases, "fracking tower bedrock gas " + gas.amount());
        checkEq(sol.amount(), 970, problems, cases, "fracking tower FRACKSOL use");
        check(level.getBlockState(pos.below(2)).is(HbmBlocks.ORE_BEDROCK_OIL.get()), problems, cases, "bedrock oil never depletes");
        tower.clearContent();
        cleanup(level, pos);
    }

    /** TileEntityHeaterOilburner: 500 kTU cap and 10 mB/t per overdrive level + 1, heat = FT_Flammable / 1000 per mB. */
