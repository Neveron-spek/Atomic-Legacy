    private static String ingredientName(net.minecraft.world.item.crafting.Ingredient ingredient) {
        for (net.minecraft.world.item.crafting.Ingredient.Value value : ingredient.getValues()) {
            if (value instanceof net.minecraft.world.item.crafting.Ingredient.TagValue tag) return tag.tag().location().toString();
            if (value instanceof net.minecraft.world.item.crafting.Ingredient.ItemValue it) return BuiltInRegistries.ITEM.getKey(it.item().getItem()).toString();
        }
        return "?";
    }

    /** PyroOvenRecipes.registerSFAuto over the port fluid traits; only the listed fluids yield solid fuel. */
    private static void pyroSolidFuel(List<String> problems, int[] cases) {
        List<String> actual = new ArrayList<>();
        for (String name : PyroOvenRecipe.SOLID_FUEL_FLUIDS) {
            HbmFluidDefinition fluid = HbmFluids.byName(name).orElse(HbmFluids.none());
            long heat = fluid.flammableHeatEnergy();
            if (heat <= 0) {
                actual.add(name + ":nonflammable");
                continue;
            }
            long target = name.equals("balefire") ? 24_000_000L : 1_440_000L;
            int mB = (int) (target * 1000L * 0.5D / heat);
            if (mB > 10_000) mB -= mB % 1000;
            else if (mB > 1_000) mB -= mB % 100;
            else if (mB > 100) mB -= mB % 10;
            mB = Math.max(mB, 1);
            actual.add(name + ":" + mB + ">atomiclegacy:" + (name.equals("balefire") ? "solid_fuel_bf" : "solid_fuel"));
        }
        compare(EXPECTED_PYRO_SF, actual, problems, cases, "pyrolysis oven solid fuel recipes");
        for (String notFuel : new String[] {"oil", "gas", "hydrogen", "heavyoil", "coaloil", "woodoil"}) {
            check(!PyroOvenRecipe.SOLID_FUEL_FLUIDS.contains(notFuel), problems, cases, "pyro oven must not make solid fuel from " + notFuel);
        }
        check(PyroOvenRecipe.floatTicks(60) >= 60 && PyroOvenRecipe.floatTicks(60) <= 61, problems, cases,
                "pyro float progress ticks for 60: " + PyroOvenRecipe.floatTicks(60));
    }

