    static int run(MinecraftServer server, List<String> problems) {
        int[] cases = {0};
        ServerLevel level = server.overworld();
        ServerLevelData data = (ServerLevelData) level.getLevelData();
        long savedTime = level.getGameTime();
        site = 0;
        try {
            recipeTables(server, problems, cases);
            pyroSolidFuel(problems, cases);
            cracker(level, data, problems, cases);
            refinery(level, problems, cases);
            derrick(level, data, problems, cases);
            fracking(level, data, problems, cases);
            oilburner(level, problems, cases);
        } catch (RuntimeException | ReflectiveOperationException e) {
            AtomicLegacy.LOGGER.error("Parity L3 diagnostics crashed", e);
            problems.add("L3 diagnostics crashed: " + e);
        } finally {
            data.setGameTime(savedTime);
            for (int[] chunk : FORCED) level.setChunkForced(chunk[0], chunk[1], false);
            FORCED.clear();
        }
        return cases[0];
    }

