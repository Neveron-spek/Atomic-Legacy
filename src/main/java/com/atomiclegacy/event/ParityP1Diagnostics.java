    private static void checkImpacts(ServerLevel level, List<String> problems, int[] cases) {
        for (var e : impacts().entrySet()) {
            cases[0]++;
            String got = String.join(", ", LegacyMissileImpacts.dryRunImpact(missile(level, new ItemStack(item(e.getKey()))), null));
            if (!got.equals(e.getValue())) problems.add("P1: impact " + e.getKey() + " = " + got + " expected " + e.getValue());
        }
        if (impacts().size() != MISSILES.size() - 1) problems.add("P1: impact table does not cover every launchable missile entity");
        for (var e : customImpacts().entrySet()) {
            cases[0]++;
            String got = String.join(", ", LegacyMissileImpacts.dryRunImpact(missile(level, custom(e.getKey(), "mp_fuselage_15_kerosene")), null));
            if (!got.equals(e.getValue())) problems.add("P1: custom impact " + e.getKey() + " = " + got + " expected " + e.getValue());
        }
        for (var e : kills().entrySet()) {
            cases[0]++;
            String got = String.join(", ", LegacyMissileImpacts.dryRunKill(missile(level, new ItemStack(item(e.getKey())))));
            if (!got.equals(e.getValue())) problems.add("P1: killMissile " + e.getKey() + " = " + got + " expected " + e.getValue());
        }
        cases[0]++;
        String customKill = String.join(", ", LegacyMissileImpacts.dryRunKill(missile(level, custom("mp_warhead_10_he", "mp_fuselage_15_kerosene"))));
        if (!customKill.equals("explodeLarge(5.0,true,false,true), shrapnelShower(15,0.075)"))
            problems.add("P1: EntityMissileCustom.killMissile drops no debris, got " + customKill);
        cases[0]++;
        LegacyLauncherMissileEntity abm = missile(level, new ItemStack(item("missile_anti_ballistic")));
        if (abm.isPickable() || abm.hurt(level.damageSources().generic(), 100F) || abm.getDeltaMovement().y != 1.5D)
            problems.add("P1: EntityMissileAntiBallistic must be unpickable, undamageable and start with motionY 1.5");
        cases[0]++;
        LegacyLauncherMissileEntity stealth = missile(level, new ItemStack(item("missile_stealth")));
        if (stealth.canBeSeenBy(null)) problems.add("P1: missile_stealth visible to radar");
    }

