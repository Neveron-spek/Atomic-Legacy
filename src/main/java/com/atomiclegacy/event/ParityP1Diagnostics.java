    private static void checkLaunch(ServerLevel level, List<String> problems, int[] cases) {
        BlockPos pos = new BlockPos(BASE_X, Y, BASE_Z);
        List<int[]> forced = new ArrayList<>();
        for (int cx = (pos.getX() - 32) >> 4; cx <= (pos.getX() + 32) >> 4; cx++)
            for (int cz = (pos.getZ() - 32) >> 4; cz <= (pos.getZ() + 32) >> 4; cz++) {
                level.setChunkForced(cx, cz, true);
                level.getChunk(cx, cz);
                forced.add(new int[] {cx, cz});
            }
        // [parity Q4: on a fresh audit world the forced tickets were not yet processed, so the spawned missile sat in an
        // inaccessible entity section; run the distance-manager update once (no chunk ticking) before using entities]
        level.getChunkSource().tick(() -> true, false);
        for (int[] c : forced) level.getChunk(c[0], c[1]);
        try {
            for (BlockPos p : BlockPos.betweenClosed(pos.offset(-3, 0, -3), pos.offset(3, 120, 3)))
                level.setBlock(p, Blocks.AIR.defaultBlockState(), 2 | 16);
            level.setBlock(pos.below(), Blocks.STONE.defaultBlockState(), 2 | 16);
            level.setBlock(pos, HbmBlocks.LAUNCH_PAD.get().defaultBlockState(), 2 | 16);
            BlockEntity be0 = level.getBlockEntity(pos);
            cases[0]++;
            if (!(be0 instanceof LauncherBlockEntity pad)) { problems.add("P1: launch_pad has no LauncherBlockEntity"); return; }
            pad.setItem(0, new ItemStack(item("missile_generic")));
            ItemStack designator = new ItemStack(item("designator"));
            CompoundTag tag = new CompoundTag();
            tag.putInt("xCoord", BASE_X + 1000);
            tag.putInt("zCoord", BASE_Z);
            designator.set(DataComponents.CUSTOM_DATA, CustomData.of(tag));
            pad.setItem(1, designator);
            setField(pad, "power", 100_000L);
            LauncherBlockEntity.tick(level, pos, level.getBlockState(pos), pad);
            if (!"ethanol".equals(pad.fuelTank().type().name()) || !"peroxide".equals(pad.oxidizerTank().type().name()))
                problems.add("P1: V2 missile tank types " + pad.fuelTank().type().name() + "/" + pad.oxidizerTank().type().name());
            pad.fuelTank().setAmount(3999);
            pad.oxidizerTank().setAmount(24_000);
            setField(pad, "power", 100_000L);
            LauncherBlockEntity.tick(level, pos, level.getBlockState(pos), pad);
            cases[0]++;
            if (pad.canLaunch() || pad.state() != LauncherBlockEntity.STATE_MISSING || (int) field(pad, "delay") != 100)
                problems.add("P1: 3999 mB ethanol must not satisfy fuelCap 4000 (state " + pad.state() + ")");
            pad.fuelTank().setAmount(24_000);
            setField(pad, "delay", 0);
            setField(pad, "power", 74_999L);
            cases[0]++;
            if (pad.canLaunch()) problems.add("P1: 74999 HE must not satisfy the 75000 HE launch cost");
            setField(pad, "power", 100_000L);
            LauncherBlockEntity.tick(level, pos, level.getBlockState(pos), pad);
            cases[0]++;
            if (pad.state() != LauncherBlockEntity.STATE_READY || !pad.canLaunch()) { problems.add("P1: fuelled silo pad not ready, state " + pad.state()); return; }
            // [parity Q1: capture the spawned missile through EntityJoinLevelEvent - on a fresh audit world the forced chunk's
            // entity section can still be hidden, so getEntitiesOfClass does not see it]
            List<LegacyLauncherMissileEntity> joined = new ArrayList<>();
            java.util.function.Consumer<net.neoforged.neoforge.event.entity.EntityJoinLevelEvent> joinListener = event -> {
                if (event.getEntity() instanceof LegacyLauncherMissileEntity missile) joined.add(missile);
            };
            net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(joinListener);
            boolean launched;
            try {
                launched = pad.launchFromDesignator();
            } finally {
                net.neoforged.neoforge.common.NeoForge.EVENT_BUS.unregister(joinListener);
            }
            if (!launched) { problems.add("P1: launchFromDesignator refused"); return; }
            cases[0]++;
            if (pad.power() != 25_000L || pad.fuelTank().amount() != 20_000 || pad.oxidizerTank().amount() != 20_000
                    || !pad.getItem(0).isEmpty() || (int) field(pad, "delay") != 100)
                problems.add("P1: launch consumption power " + pad.power() + " fuel " + pad.fuelTank().amount() + "/" + pad.oxidizerTank().amount()
                        + " slot " + pad.getItem(0) + " delay " + field(pad, "delay"));
            List<LegacyLauncherMissileEntity> spawned = new ArrayList<>(level.getEntitiesOfClass(LegacyLauncherMissileEntity.class, new AABB(pos).inflate(4)));
            for (LegacyLauncherMissileEntity missile : joined) if (!spawned.contains(missile)) spawned.add(missile);
            cases[0]++;
            if (spawned.size() != 1) { problems.add("P1: expected one launched missile, got " + spawned.size()); return; }
            LegacyLauncherMissileEntity m = spawned.get(0);
            try {
                if (Math.abs(m.getX() - (BASE_X + 0.5)) > 1e-6 || Math.abs(m.getY() - (Y + 1)) > 1e-6 || Math.abs(m.getZ() - (BASE_Z + 0.5)) > 1e-6)
                    problems.add("P1: launch position " + m.position());
                checkTrajectory(m, problems, cases);
            } finally {
                m.discard();
            }
        } catch (ReflectiveOperationException ex) {
            problems.add("P1: reflection failed: " + ex);
        } finally {
            for (BlockPos p : BlockPos.betweenClosed(pos.offset(-3, -1, -3), pos.offset(3, 120, 3))) {
                if (level.getBlockEntity(p) instanceof net.minecraft.world.Container c) c.clearContent();
                if (!level.getBlockState(p).isAir()) level.setBlock(p, Blocks.AIR.defaultBlockState(), 2 | 16);
            }
            for (int[] c : forced) level.setChunkForced(c[0], c[1], false);
        }
    }

    /** EntityMissileBaseNT.onUpdate recurrence (EntityThrowableNT moves by motion * velocity first). */
    private static void checkTrajectory(LegacyLauncherMissileEntity m, List<String> problems, int[] cases) {
        double sx = (int) (float) m.getX(), sz = (int) (float) m.getZ(), tx = BASE_X + 1000, tz = BASE_Z;
        double len = Math.sqrt((tx - sx) * (tx - sx) + (tz - sz) * (tz - sz));
        double accel = 1 / len, decel = 2 / len, vel = 0;
        double x = m.getX(), y = m.getY(), z = m.getZ(), mx = 0, my = 2, mz = 0;
        for (int t = 1; t <= 40; t++) {
            x += mx * vel; y += my * vel; z += mz * vel;
            if (vel < 4) vel += Mth.clamp(t / 60D * 0.05D, 0, 0.05);
            my -= decel * vel;
            double nx = (tx - sx) / len * accel, nz = (tz - sz) / len * accel;
            if (my > 0) { mx += nx * vel; mz += nz * vel; }
            if (my < 0) { mx -= nx * vel; mz -= nz * vel; }
            m.tickCount++;
            m.tick();
            if (m.isRemoved()) { problems.add("P1: missile removed at tick " + t); return; }
            if (Math.abs(m.getX() - x) > 1e-6 || Math.abs(m.getY() - y) > 1e-6 || Math.abs(m.getZ() - z) > 1e-6
                    || Math.abs(m.velocity() - vel) > 1e-9) {
                problems.add("P1: trajectory tick " + t + " port " + m.position() + " v" + m.velocity() + " expected " + new Vec3(x, y, z) + " v" + vel);
                return;
            }
        }
        cases[0] += 40;
    }

    private static void checkRecipes(MinecraftServer server, List<String> problems, int[] cases) {
        var manager = server.getRecipeManager();
        for (String line : RECIPES) {
            String[] f = line.split("\\|");
            cases[0]++;
            var holder = manager.byKey(AtomicLegacy.id(f[1]));
            if (holder.isEmpty()) { problems.add("P1: recipe " + f[0] + " (" + f[1] + ") not loaded"); continue; }
            ItemStack result = holder.get().value().getResultItem(server.registryAccess());
            ResourceLocation rid = BuiltInRegistries.ITEM.getKey(result.getItem());
            if (!rid.getPath().equals(f[4])) problems.add("P1: recipe " + f[1] + " result " + rid + " expected " + f[4]);
        }
    }
