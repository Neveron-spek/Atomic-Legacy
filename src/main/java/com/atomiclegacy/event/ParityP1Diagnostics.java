    static int run(MinecraftServer server, List<String> problems) {
        ServerLevel level = server.overworld();
        int[] cases = {0};
        List<Runnable> checks = List.of(() -> checkMissiles(problems, cases), () -> checkParts(problems, cases),
                () -> checkImpacts(level, problems, cases), () -> checkCustomBlip(level, problems, cases),
                () -> checkLaunch(level, problems, cases), () -> checkRecipes(server, problems, cases));
        for (Runnable check : checks) {
            try {
                check.run();
            } catch (RuntimeException ex) {
                problems.add("P1: check aborted: " + ex);
            }
        }
        return cases[0];
    }

    private static Item item(String id) {
        return BuiltInRegistries.ITEM.get(AtomicLegacy.id(id));
    }

    private static void checkMissiles(List<String> problems, int[] cases) {
        for (String line : MISSILES) {
            String[] f = line.split("\\|");
            cases[0]++;
            if (!(item(f[0]) instanceof LegacyMissileItem m)) { problems.add("P1: " + f[0] + " is not a LegacyMissileItem"); continue; }
            String got = f[0] + "|" + m.formFactor() + "|" + m.tier() + "|" + m.fuel() + "|" + m.fuelCapacity() + "|" + m.launchable();
            if (!got.equals(line)) problems.add("P1: missile " + got + " expected " + line);
            if (new ItemStack(m).getMaxStackSize() != 1) problems.add("P1: " + f[0] + " stack size != 1");
        }
    }

    private static void checkParts(List<String> problems, int[] cases) {
        for (String line : PARTS) {
            String id = line.substring(0, line.indexOf('|'));
            cases[0]++;
            if (!(item(id) instanceof MissilePartItem part)) { problems.add("P1: part " + id + " missing"); continue; }
            MissilePartItem.Definition d = part.definition();
            String got = id + "|" + d.type() + "|" + d.top() + "|" + d.bottom() + "|" + (d.fuel() == null ? "-" : d.fuel())
                    + "|" + (d.warhead() == null ? "-" : d.warhead()) + "|" + d.primary() + "|" + d.secondary() + "|" + d.health();
            if (!got.equals(line)) problems.add("P1: part " + got + " expected " + line);
        }
    }

