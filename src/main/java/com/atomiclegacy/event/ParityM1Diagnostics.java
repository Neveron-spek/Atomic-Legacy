    static int run(MinecraftServer server, List<String> problems) {
        int[] cases = {0};
        ServerLevel level = server.overworld();
        List<int[]> forced = new ArrayList<>();
        try {
            rodTable(problems, cases);
            rodCases(problems, cases);
            reactor(level, forced, problems, cases);
            meltdown(level, forced, problems, cases);
        } catch (RuntimeException | ReflectiveOperationException e) {
            AtomicLegacy.LOGGER.error("Parity M1 diagnostics crashed", e);
            problems.add("M1 diagnostics crashed: " + e);
        } finally {
            for (int[] chunk : forced) level.setChunkForced(chunk[0], chunk[1], false);
        }
        return cases[0];
    }

    private static Item item(String id) {
        return BuiltInRegistries.ITEM.get(ResourceLocation.fromNamespaceAndPath(AtomicLegacy.MOD_ID, id));
    }

    private static boolean near(double expected, double actual) {
        return Math.abs(expected - actual) <= 1.0E-9D * Math.max(1.0D, Math.abs(expected));
    }

    private static void rodTable(List<String> problems, int[] cases) {
        int ported = 0;
        for (Item candidate : BuiltInRegistries.ITEM) {
            if (candidate instanceof RbmkFuelRodItem) ported++;
        }
        cases[0]++;
        if (ported != ROD_TABLE.length) problems.add("M1: rod count " + ported + " != " + ROD_TABLE.length);
        for (String row : ROD_TABLE) {
            String[] expected = row.split("\\|", -1);
            String id = expected[0].equals("hep239") ? "hep" : expected[0];
            Item rodItem = item("rbmk_fuel_" + id);
            cases[0]++;
            if (!(rodItem instanceof RbmkFuelRodItem rod)) {
                problems.add("M1: missing rod rbmk_fuel_" + id);
                continue;
            }
            String[] actual = rod.parityDescriptor().split("\\|", -1);
            for (int i = 1; i < expected.length; i++) {
                boolean same;
                try {
                    same = Double.parseDouble(expected[i]) == Double.parseDouble(actual[i]);
                } catch (NumberFormatException e) {
                    same = expected[i].equals(actual[i]);
                }
                if (!same) problems.add("M1: rod " + id + " field " + i + " expected " + expected[i] + " got " + actual[i]);
            }
        }
    }

    private static void rodCases(List<String> problems, int[] cases) {
        for (String row : ROD_CASES) {
            String[] v = row.split("\\|");
            String id = v[0];
            RbmkFuelRodItem rod = (RbmkFuelRodItem) item("rbmk_fuel_" + id);
            ItemStack stack = new ItemStack(rod);
            int k = 1;
            for (int i = 0; i < 20; i++) {
                RbmkFuelRodItem.FuelTickResult r = rod.burnAndProvideHeat(stack, 50.0D + i * 7.0D, 300.0D,
                        1.0D, 1.0D, 0.2D, true, true);
                cases[0]++;
                double out = Double.parseDouble(v[k++]);
                double prov = Double.parseDouble(v[k++]);
                if (!near(out, r.outputFlux()) || !near(prov, r.providedHeat())) {
                    problems.add("M1: rod " + id + " step " + i + " flux/heat " + r.outputFlux() + "/" + r.providedHeat()
                            + " expected " + out + "/" + prov);
                    break;
                }
            }
            double melt = Double.parseDouble(ROD_TABLE_MELT(id));
            RbmkFuelRodItem.setState(stack, RbmkFuelRodItem.depletion(stack), RbmkFuelRodItem.xenon(stack),
                    Math.max(RbmkFuelRodItem.coreHeat(stack), melt + 1.0D), melt + 1.0D);
            RbmkFuelRodItem.FuelTickResult r = rod.burnAndProvideHeat(stack, 0.0D, 300.0D, 1.0D, 1.0D, 0.2D, true, true);
            double[] got = {r.outputFlux(), r.providedHeat(), RbmkFuelRodItem.coreHeat(stack), RbmkFuelRodItem.hullHeat(stack),
                    RbmkFuelRodItem.depletion(stack), RbmkFuelRodItem.xenon(stack) * 100.0D};
            String[] names = {"flux", "heat", "core", "hull", "depletion", "xenon"};
            k = 41;
            for (int i = 0; i < got.length; i++) {
                cases[0]++;
                double expected = Double.parseDouble(v[k + i]);
                if (!(Math.abs(expected - got[i]) <= 1.0E-7D * Math.max(1.0D, Math.abs(expected)))) {
                    problems.add("M1: rod " + id + " hull-melt " + names[i] + " " + got[i] + " expected " + expected);
                }
            }
        }
    }

