    /** Ticks of ModuleMachineBase#process until progress >= 1, starting from {@code start}. */
    private static int cycleTicks(int duration, double speed, double start) {
        double progress = start;
        int ticks = 0;
        while (progress < 1.0D) {
            progress += Math.min(speed / duration, 1.0D);
            ticks++;
        }
        return ticks;
    }

    private static double carry(int duration, double speed, int ticks) {
        double progress = 0.0D;
        for (int i = 0; i < ticks; i++) {
            progress += Math.min(speed / duration, 1.0D);
        }
        return progress - 1.0D;
    }

    private static String fluidKey(HbmFluidDefinition type, int amount, int pressure) {
        return type.legacyFieldName().toLowerCase(Locale.ROOT) + ":" + amount + ":" + pressure;
    }

    private static String join(List<Integer> values) {
        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) {
                builder.append(',');
            }
            builder.append(values.get(i));
        }
        return builder.toString();
    }

    private static Item item(String path) {
        return BuiltInRegistries.ITEM.get(AtomicLegacy.id(path));
    }

    private static void tick(AssemblyMachineBlockEntity machine, int ticks) {
        for (int i = 0; i < ticks; i++) {
            AssemblyMachineBlockEntity.tick(machine.getLevel(), machine.getBlockPos(), machine.getLevel().getBlockState(machine.getBlockPos()), machine);
        }
    }

    private static void tickChem(ChemicalPlantBlockEntity machine, int ticks) {
        for (int i = 0; i < ticks; i++) {
            ChemicalPlantBlockEntity.tick(machine.getLevel(), machine.getBlockPos(), machine.getLevel().getBlockState(machine.getBlockPos()), machine);
        }
    }

    private static AssemblyMachineBlockEntity assembler(ServerLevel level) {
        BlockEntity be = place(level, HbmBlocks.MACHINE_ASSEMBLY_MACHINE.get());
        if (!(be instanceof AssemblyMachineBlockEntity machine)) {
            throw new IllegalStateException("assembly machine has no block entity");
        }
        return machine;
    }

    private static ChemicalPlantBlockEntity chemplant(ServerLevel level) {
        BlockEntity be = place(level, HbmBlocks.MACHINE_CHEMICAL_PLANT.get());
        if (!(be instanceof ChemicalPlantBlockEntity machine)) {
            throw new IllegalStateException("chemical plant has no block entity");
        }
        return machine;
    }

    /** Places the machine core on its own stone pad (one per site) and returns the block entity. */
    private static BlockEntity place(ServerLevel level, Block block) {
        int index = site++;
        BlockPos pos = new BlockPos(BASE_X + (index % 8) * SPACING, BASE_Y, BASE_Z + (index / 8) * SPACING);
        int cx = pos.getX() >> 4;
        int cz = pos.getZ() >> 4;
        level.setChunkForced(cx, cz, true);
        level.getChunk(cx, cz);
        FORCED.add(new int[] {cx, cz});
        for (int dx = -2; dx <= 2; dx++) {
            for (int dz = -2; dz <= 2; dz++) {
                level.setBlock(pos.offset(dx, -1, dz), Blocks.STONE.defaultBlockState(), 2 | 16);
                for (int dy = 0; dy <= 3; dy++) {
                    level.setBlock(pos.offset(dx, dy, dz), Blocks.AIR.defaultBlockState(), 2 | 16);
                }
            }
        }
        level.setBlock(pos, block.defaultBlockState(), 3);
        return level.getBlockEntity(pos);
    }

    private static void check(boolean condition, List<String> problems, int[] cases, String message) {
        cases[0]++;
        if (!condition) {
            problems.add("K3-D: " + message);
        }
    }

